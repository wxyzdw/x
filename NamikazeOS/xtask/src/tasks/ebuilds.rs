pub(crate) fn run(root: &Path) -> Result<()> {
    let ver = gentoo_from(namikaze_common::VERSION);
    let mut written = 0;
    for (crate_name, dir) in EBUILD_SECTORS {
        let target =
            root.join("overlay/sys-namikaze").join(dir).join(format!("{crate_name}-{ver}.ebuild"));
        if target.exists() {
            continue; // curated ebuilds stay; only missing ones are generated
        }
        std::fs::create_dir_all(target.parent().unwrap())?;
        let body = format!(
            r#"# Generated by cargo xtask ebuilds; edit by hand only with care.
EAPI=8

DESCRIPTION="NamikazeOS {crate_name} component"
HOMEPAGE="https://github.com/wxyzdw/x"
SRC_URI=""

LICENSE="MPL-2.0"
SLOT="0"
KEYWORDS="~amd64 ~arm64"
IUSE=""

DEPEND=""
RDEPEND="${{DEPEND}}"
BDEPEND=""

S="${{WORKDIR}}"

src_install() {{
    # binary is supplied by the workspace release artifact
    exeinto /usr/bin
    newexe "${{FILESDIR}}/placeholder" {crate_name}
}}
"#
        );
        std::fs::write(&target, body)?;
        written += 1;
    }
    println!(
        "ebuilds: {written} generated ({}/{} total known)",
        EBUILD_SECTORS.len(),
        EBUILD_SECTORS.len()
    );
    Ok(())
}
