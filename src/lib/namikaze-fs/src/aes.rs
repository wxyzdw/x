/// Multiplication by x in GF(2^8) modulo the AES polynomial.
fn xtime(b: u8) -> u8 {
    (b << 1) ^ if b & 0x80 != 0 { 0x1b } else { 0 }
}

/// Multiply two elements of GF(2^8) (Russian peasant method).
fn gmul(a: u8, b: u8) -> u8 {
    let (mut a, mut b, mut out) = (a, b, 0u8);
    for _ in 0..8 {
        if b & 1 != 0 {
            out ^= a;
        }
        a = xtime(a);
        b >>= 1;
    }
    out
}

/// Expanded AES-256 key: 15 round keys of 16 bytes.
pub struct Aes256 {
    round_keys: [[u8; 16]; 15],
}

impl Aes256 {
    /// Expand a 32-byte key (FIPS-197 key expansion, Nk=8, Nr=14).
    pub fn new(key: &[u8; 32]) -> Self {
        let mut w = [[0u8; 4]; 60];
        for (i, word) in w.iter_mut().take(8).enumerate() {
            word.copy_from_slice(&key[i * 4..i * 4 + 4]);
        }
        let mut rcon = 1u8;
        for i in 8..60 {
            let mut temp = w[i - 1];
            if i % 8 == 0 {
                temp = [
                    SBOX[temp[1] as usize],
                    SBOX[temp[2] as usize],
                    SBOX[temp[3] as usize],
                    SBOX[temp[0] as usize],
                ];
                temp[0] ^= rcon;
                rcon = xtime(rcon);
            } else if i % 8 == 4 {
                temp = temp.map(|b| SBOX[b as usize]);
            }
            for j in 0..4 {
                w[i][j] = w[i - 8][j] ^ temp[j];
            }
        }
        let mut round_keys = [[0u8; 16]; 15];
        for (rk, chunk) in round_keys.iter_mut().zip(w.chunks(4)) {
            for col in 0..4 {
                for row in 0..4 {
                    rk[col * 4 + row] = chunk[col][row];
                }
            }
        }
        Self { round_keys }
    }

    /// Encrypt one 16-byte block in place.
    pub fn encrypt_block(&self, block: &mut [u8; 16]) {
        add_round_key(block, &self.round_keys[0]);
        for round in 1..14 {
            sub_bytes(block);
            shift_rows(block);
            mix_columns(block);
            add_round_key(block, &self.round_keys[round]);
        }
        sub_bytes(block);
        shift_rows(block);
        add_round_key(block, &self.round_keys[14]);
    }

    /// Decrypt one 16-byte block in place.
    pub fn decrypt_block(&self, block: &mut [u8; 16]) {
        add_round_key(block, &self.round_keys[14]);
        for round in (1..14).rev() {
            inv_shift_rows(block);
            inv_sub_bytes(block);
            add_round_key(block, &self.round_keys[round]);
            inv_mix_columns(block);
        }
        inv_shift_rows(block);
        inv_sub_bytes(block);
        add_round_key(block, &self.round_keys[0]);
    }
}

fn add_round_key(block: &mut [u8; 16], rk: &[u8; 16]) {
    for (b, k) in block.iter_mut().zip(rk) {
        *b ^= k;
    }
}

fn sub_bytes(block: &mut [u8; 16]) {
    for b in block.iter_mut() {
        *b = SBOX[*b as usize];
    }
}

fn inv_sub_bytes(block: &mut [u8; 16]) {
    for b in block.iter_mut() {
        *b = INV_SBOX[*b as usize];
    }
}

fn shift_rows(block: &mut [u8; 16]) {
    // state is column-major: row r of the matrix is block[r], block[r+4], ...
    let mut out = *block;
    for r in 0..4 {
        for c in 0..4 {
            out[c * 4 + r] = block[((c + r) % 4) * 4 + r];
        }
    }
    *block = out;
}

fn inv_shift_rows(block: &mut [u8; 16]) {
    let mut out = *block;
    for r in 0..4 {
        for c in 0..4 {
            out[c * 4 + r] = block[((c + 4 - r) % 4) * 4 + r];
        }
    }
    *block = out;
}

fn mix_columns(block: &mut [u8; 16]) {
    for c in 0..4 {
        let col = &mut block[c * 4..c * 4 + 4];
        let a = [col[0], col[1], col[2], col[3]];
        col[0] = gmul(a[0], 2) ^ gmul(a[1], 3) ^ a[2] ^ a[3];
        col[1] = a[0] ^ gmul(a[1], 2) ^ gmul(a[2], 3) ^ a[3];
        col[2] = a[0] ^ a[1] ^ gmul(a[2], 2) ^ gmul(a[3], 3);
        col[3] = gmul(a[0], 3) ^ a[1] ^ a[2] ^ gmul(a[3], 2);
    }
}

fn inv_mix_columns(block: &mut [u8; 16]) {
    for c in 0..4 {
        let col = &mut block[c * 4..c * 4 + 4];
        let a = [col[0], col[1], col[2], col[3]];
        col[0] = gmul(a[0], 14) ^ gmul(a[1], 11) ^ gmul(a[2], 13) ^ gmul(a[3], 9);
        col[1] = gmul(a[0], 9) ^ gmul(a[1], 14) ^ gmul(a[2], 11) ^ gmul(a[3], 13);
        col[2] = gmul(a[0], 13) ^ gmul(a[1], 9) ^ gmul(a[2], 14) ^ gmul(a[3], 11);
        col[3] = gmul(a[0], 11) ^ gmul(a[1], 13) ^ gmul(a[2], 9) ^ gmul(a[3], 14);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// FIPS-197 appendix C.3 (AES-256 known-answer test).
    #[test]
    fn fips197_c3_vector() {
        let key: [u8; 32] = (0u8..32).collect::<Vec<_>>().try_into().unwrap();
        let mut block: [u8; 16] = [
            0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd,
            0xee, 0xff,
        ];
        Aes256::new(&key).encrypt_block(&mut block);
        let expect = [
            0x8e, 0xa2, 0xb7, 0xca, 0x51, 0x67, 0x45, 0xbf, 0xea, 0xfc, 0x49, 0x90, 0x4b, 0x49,
            0x60, 0x89,
        ];
        assert_eq!(block, expect);
        Aes256::new(&key).decrypt_block(&mut block);
        assert_eq!(
            block,
            [
                0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd,
                0xee, 0xff
            ]
        );
    }

    #[test]
    fn gf_arithmetic() {
        assert_eq!(xtime(0x80), 0x1b); // 0x100 reduces to 0x1b via the AES polynomial
        assert_eq!(gmul(0x57, 0x13), 0xfe); // classic FIPS-197 example
        assert_eq!(gmul(0x02, 0x87), 0x15);
    }
}
