//! Pure rescue planning. A rescue environment boots the same sealed live
//! image with repair affordances enabled, then lets the operator chroot
//! into a slot. Everything is rendered text so it can be reviewed offline.

#![forbid(unsafe_code)]

/// The rescue target: which boot tree to reuse and where the image slots live.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RescueTarget {
    /// Boot tree name, matching the Limine ${ARCH} macro value (x86-64, ...)
    pub tree: String,
    /// Directory holding current/, previous/ and staged/ image slots
    pub slots_dir: String,
}

/// The rendered rescue plan.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RescuePlan {
    pub target: RescueTarget,
}

impl RescuePlan {
    pub fn build(target: &RescueTarget) -> Self {
        Self { target: target.clone() }
    }

    /// Limine menu entry for the rescue boot (appended to limine.conf).
    pub fn render_entry(&self) -> String {
        format!(
            "/NamikazeOS (rescue - repair mode)\n    comment: Offline rescue; the seal stays closed, persist left closed.\n    protocol: linux\n    path: boot():/boot/{}/vmlinuz\n    module_path: boot():/boot/{}/initrd.img\n    cmdline: namikaze.live=volatile namikaze.recovery=yes namikaze.rescue=yes\n",
            self.target.tree, self.target.tree
        )
    }

    /// Operator recipe for chrooting into an image slot, with the safety
    /// ordering spelled out (verify hashes before mounting, never mount
    /// both slots, leave the persist volume closed unless asked).
    pub fn render_recipe(&self) -> String {
        format!(
            "#!/bin/sh\n\
             # generated by namikaze-rescue; review before running\n\
             set -eu\n\
             SLOTS={slots}\n\
             cd \"$SLOTS/current\"\n\
             sha256sum -c rootfs.img.sha256\n\
             mkdir -p /mnt/rescue\n\
             mount -o ro \"$SLOTS/current/rootfs.img\" /mnt/rescue\n\
             echo 'slot mounted read-only at /mnt/rescue; re-mount rw only after backing up'\n\
             # chroot /mnt/rescue /bin/sh -l\n",
            slots = self.target.slots_dir
        )
    }

    /// Ordering constraints every rescue session must respect.
    pub fn constraints(&self) -> Vec<String> {
        vec![
            "dm-verity is disabled for the rescue image itself; the slots must be hash-verified manually".into(),
            "the persist volume stays closed unless the operator explicitly opens it".into(),
            "network is down by default; rescue never phones home".into(),
            "never mount current/ and previous/ at the same time".into(),
        ]
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn target() -> RescueTarget {
        RescueTarget { tree: "x86-64".into(), slots_dir: "/var/lib/namikaze/updates".into() }
    }

    #[test]
    fn entry_points_at_tree_and_disables_verification() {
        let plan = RescuePlan::build(&target());
        let entry = plan.render_entry();
        assert!(entry.contains("/boot/x86-64/vmlinuz"));
        assert!(entry.contains("namikaze.recovery=yes"));
        assert!(entry.contains("namikaze.rescue=yes"));
        assert!(entry.contains("namikaze.live=volatile"));
        assert!(!entry.contains("CDLABEL"));
    }

    #[test]
    fn recipe_hashes_before_mounting() {
        let plan = RescuePlan::build(&target());
        let recipe = plan.render_recipe();
        let hash_pos = recipe.find("sha256sum -c").expect("hash step");
        let mount_pos = recipe.find("mount -o ro").expect("mount step");
        assert!(hash_pos < mount_pos, "verify before mount");
    }

    #[test]
    fn constraints_name_the_invariants() {
        let plan = RescuePlan::build(&target());
        let c = plan.constraints();
        assert_eq!(c.len(), 4);
        assert!(c.iter().any(|x| x.contains("persist volume stays closed")));
    }

    #[test]
    fn aarch64_tree_flows_through() {
        let t = RescueTarget { tree: "aarch64".into(), ..target() };
        let plan = RescuePlan::build(&t);
        assert!(plan.render_entry().contains("/boot/aarch64/vmlinuz"));
    }
}
